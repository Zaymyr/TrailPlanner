import { getRenderOutputObject, type VideoRenderJobRow } from "./video-render";
import { isInstagramPublishDryRun } from "./instagram/config";
import { buildDraftPrefill, parseReelContent } from "./reel-content";
import { createSocialPostRepository, type SocialPostRepository, type SocialPostRow } from "./social-posts";
import type { SupabaseServiceConfig } from "./supabase";

type DraftJob = Pick<VideoRenderJobRow, "id" | "race_id" | "content">;

/**
 * Insert payload of a draft made from a finished render: shared by the admin route and the
 * automatic draft. The reel text of the video is copied as is (full JSON) into `content`.
 */
export const buildSocialPostDraftRow = ({ job, caption, hashtags, coverText, createdBy, autoGenerated = false }: {
  job: DraftJob;
  caption: string;
  hashtags: string[];
  coverText: string | null;
  createdBy: string | null;
  autoGenerated?: boolean;
}) => {
  const reelContent = parseReelContent(job.content);
  return {
    race_id: job.race_id,
    video_job_id: job.id,
    platform: "instagram",
    status: "draft",
    caption,
    hashtags,
    cover_text: coverText || null,
    ...(reelContent ? { content: reelContent } : {}),
    video_url: getRenderOutputObject(job.id),
    dry_run: isInstagramPublishDryRun(),
    created_by: createdBy,
    ...(autoGenerated ? { auto_generated: true } : {}),
  };
};

/**
 * One-click reel: the draft created when a render launched with `auto_draft` is done. Always a
 * `draft` (never scheduled or published), owned by the admin who launched the render, pre-filled
 * from the reel text of the job exactly like a manual draft. Idempotent: an existing automatic
 * draft is returned as is (a retried completion callback creates nothing), and the partial unique
 * index of the migration closes the race between two concurrent callbacks.
 */
export const createAutoDraftForRenderJob = async (
  supabase: SupabaseServiceConfig,
  job: Pick<VideoRenderJobRow, "id" | "race_id" | "race_title" | "content" | "created_by" | "auto_draft">,
  repository: SocialPostRepository = createSocialPostRepository(supabase),
): Promise<{ post: SocialPostRow; created: boolean } | null> => {
  const content = parseReelContent(job.content);
  if (!job.auto_draft || !content) return null;

  const existing = await repository.findAutoDraft(job.id);
  if (existing) return { post: existing, created: false };

  const prefill = buildDraftPrefill(job.race_title, content);
  try {
    const post = await repository.insert(buildSocialPostDraftRow({
      job,
      caption: prefill.caption,
      hashtags: prefill.hashtags,
      coverText: prefill.coverText,
      createdBy: job.created_by,
      autoGenerated: true,
    }));
    return { post, created: true };
  } catch (error) {
    // A concurrent callback won the unique index: its draft is the one.
    const winner = await repository.findAutoDraft(job.id).catch(() => null);
    if (winner) return { post: winner, created: false };
    throw error;
  }
};
