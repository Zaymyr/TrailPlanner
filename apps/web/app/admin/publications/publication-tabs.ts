import { formatParisDateTime, type PublicSocialPost } from "../../../lib/social-posts";
import { CAROUSEL_MARK, CAROUSEL_SERIES_NAMES } from "./automation-labels";
import type { RenderActivityView } from "./publications-api";

/**
 * Tabs of the Publications admin (pure): Agenda (what needs a look + calendar), Reels and
 * Carrousels (prepare and control), Survols (organizer flyover orders), GPX à traiter (missing race
 * data), Publiées (history), Paramètres (switches, Instagram account).
 */

export const PUBLICATION_TABS = [
  { id: "agenda", label: "Agenda" },
  { id: "reels", label: "Reels" },
  { id: "carousels", label: "Carrousels" },
  { id: "flyovers", label: "Survols" },
  { id: "gpx", label: "GPX à traiter" },
  { id: "published", label: "Publiées" },
  { id: "settings", label: "Paramètres" },
] as const;
export type PublicationTab = (typeof PUBLICATION_TABS)[number]["id"];

/** `?onglet=reels` opens that tab; anything else opens the agenda. */
export const readTabFromLocation = (search: string): PublicationTab => {
  const value = new URLSearchParams(search).get("onglet");
  return PUBLICATION_TABS.find((tab) => tab.id === value)?.id ?? "agenda";
};

export const tabForPost = (post: Pick<PublicSocialPost, "status" | "mediaType">): PublicationTab =>
  post.status === "published" ? "published" : post.mediaType === "carousel" ? "carousels" : "reels";

export const postTitle = (post: Pick<PublicSocialPost, "mediaType" | "carouselSeries" | "raceTitle">) =>
  post.mediaType === "carousel"
    ? `${CAROUSEL_MARK} ${post.carouselSeries ? CAROUSEL_SERIES_NAMES[post.carouselSeries] : "Carrousel"}${post.raceTitle ? ` · ${post.raceTitle}` : ""}`
    : post.raceTitle ?? "Reel";

export type AttentionEntry = {
  key: string;
  /** Changes with the state of the alert: a dismissed alert comes back when it changes (a new failure, a new date). */
  dismissKey: string;
  tone: "active" | "error" | "todo" | "scheduled";
  title: string;
  detail: string;
  target: { tab: PublicationTab; postId?: string };
};

const UPCOMING_MS = 7 * 24 * 60 * 60 * 1_000;
const TONE_ORDER: Record<AttentionEntry["tone"], number> = { active: 0, error: 1, todo: 2, scheduled: 3 };

/**
 * « À surveiller »: renders running or failed in the last 24 h, posts publishing, failed or waiting
 * for review, then what is scheduled in the next 7 days (soonest first).
 */
export const buildAttentionList = ({ posts, renders, nowMs }: { posts: PublicSocialPost[]; renders: RenderActivityView[]; nowMs: number }): AttentionEntry[] => {
  const entries: Array<AttentionEntry & { sortAt: number }> = [];
  renders.forEach((render) => {
    if (render.status === "done") return;
    entries.push({
      key: `render-${render.id}`,
      dismissKey: `render-${render.id}:${render.status}`,
      tone: render.status === "active" ? "active" : "error",
      title: render.kind === "carousel" ? `${CAROUSEL_MARK} ${render.title}` : `Rendu · ${render.title}`,
      detail: render.stage,
      target: { tab: render.kind === "carousel" ? "carousels" : "reels" },
      sortAt: Date.parse(render.createdAt),
    });
  });
  posts.forEach((post) => {
    const base = { key: `post-${post.id}`, dismissKey: `post-${post.id}:${post.status}:${post.error ?? post.scheduledAt ?? ""}`, title: postTitle(post), target: { tab: tabForPost(post), postId: post.id } };
    if (post.status === "publishing") entries.push({ ...base, tone: "active", detail: "Publication en cours sur Instagram", sortAt: 0 });
    else if (post.status === "failed") entries.push({ ...base, tone: "error", detail: `Échec : ${post.error ?? "raison inconnue"}`, sortAt: 0 });
    else if (post.status === "draft") entries.push({ ...base, tone: "todo", detail: post.autoGenerated ? "Brouillon automatique à relire" : "Brouillon à relire", sortAt: 0 });
    else if (post.status === "scheduled" && post.scheduledAt) {
      const at = Date.parse(post.scheduledAt);
      if (at - nowMs <= UPCOMING_MS) entries.push({ ...base, tone: "scheduled", detail: `Programmé le ${formatParisDateTime(post.scheduledAt)}${post.dryRun ? " (simulation)" : ""}`, sortAt: at });
    }
  });
  return entries
    .sort((left, right) => TONE_ORDER[left.tone] - TONE_ORDER[right.tone] || (left.tone === "scheduled" ? left.sortAt - right.sortAt : right.sortAt - left.sortAt))
    .map(({ sortAt: _sortAt, ...entry }) => entry);
};

/** Alerts the admin hid in this browser (« Masquer »). */
export const DISMISSED_ATTENTION_STORAGE_KEY = "admin.publications.dismissed-alerts";

export const readDismissedAlerts = (): Set<string> => {
  try {
    const raw = window.localStorage.getItem(DISMISSED_ATTENTION_STORAGE_KEY);
    const parsed: unknown = raw ? JSON.parse(raw) : [];
    return new Set(Array.isArray(parsed) ? parsed.filter((value): value is string => typeof value === "string") : []);
  } catch {
    return new Set();
  }
};

/** Keeps only the keys still on the list, so the stored set never grows. */
export const writeDismissedAlerts = (dismissed: Set<string>, current: AttentionEntry[]) => {
  const live = new Set(current.map((entry) => entry.dismissKey));
  const kept = Array.from(dismissed).filter((key) => live.has(key));
  try {
    window.localStorage.setItem(DISMISSED_ATTENTION_STORAGE_KEY, JSON.stringify(kept));
  } catch {
    // Private mode or blocked storage: the alert is hidden until the page reloads.
  }
  return new Set(kept);
};

/**
 * Tabs of the console page « Publications » (`/admin/content/posts`, lot 1 of the admin console):
 * Reels, Carrousels and Publiées come from the former Publications page, « Templates sociaux » is the
 * manual carousel of the former /admin tab. `?onglet=` selects one (Reels when absent).
 */
export const POSTS_TABS = [
  { id: "reels", label: "Reels" },
  { id: "carousels", label: "Carrousels" },
  { id: "published", label: "Publiées" },
  { id: "templates", label: "Templates sociaux" },
] as const;
export type PostsTab = (typeof POSTS_TABS)[number]["id"];

export const readPostsTab = (search: string): PostsTab => {
  const value = new URLSearchParams(search).get("onglet");
  return POSTS_TABS.find((tab) => tab.id === value)?.id ?? "reels";
};

/** The post (`?post=`) or plan item (`?element=`) to highlight when the page opens. */
export const readPostsHighlight = (search: string) => {
  const params = new URLSearchParams(search);
  return { postId: params.get("post")?.trim() || null, itemId: params.get("element")?.trim() || null };
};

/** Console URL of an agenda or calendar target (« Voir »): the Publications tab plus the item to highlight. */
export const publicationTargetHref = (target: { tab: PublicationTab; postId?: string; itemId?: string }): string => {
  const params = new URLSearchParams();
  if (target.tab === "carousels" || target.tab === "published") params.set("onglet", target.tab);
  if (target.postId) params.set("post", target.postId);
  else if (target.itemId) params.set("element", target.itemId);
  const search = params.toString();
  const base =
    target.tab === "agenda" ? "/admin/content"
    : target.tab === "flyovers" ? "/admin/content/flyovers"
    : target.tab === "gpx" ? "/admin/catalog/races?vue=qualite"
    : target.tab === "settings" ? "/admin/system/automation"
    : "/admin/content/posts";
  if (base !== "/admin/content/posts") return base;
  return search ? `${base}?${search}` : base;
};
