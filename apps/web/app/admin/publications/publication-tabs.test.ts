import { describe, expect, it } from "vitest";

import type { PublicSocialPost } from "../../../lib/social-posts";
import { buildAttentionList, POSTS_TABS, postTitle, publicationTargetHref, readPostsHighlight, readPostsTab, readTabFromLocation, summarizeRenderActivity, tabForPost } from "./publication-tabs";
import type { RenderActivityView } from "./publications-api";

const NOW = Date.parse("2026-11-20T15:00:00Z");

const post = (overrides: Partial<PublicSocialPost>): PublicSocialPost => ({
  mediaType: "reel", carouselSeries: null, carouselJobId: null, slideCount: 0,
  id: "p", raceId: null, videoJobId: null, raceTitle: "Hivernale des Templiers", status: "draft",
  caption: "", hashtags: [], coverText: null, scheduledAt: null, publishedAt: null, igMediaId: null, igPermalink: null,
  hasContainer: false, publishRequested: false, error: null, dryRun: false, autoGenerated: false,
  ...overrides,
} as PublicSocialPost);

const render = (overrides: Partial<RenderActivityView>): RenderActivityView => ({
  id: "r", kind: "reel", title: "SaintéLyon", status: "active", progress: 0.3, stage: "Rendu vidéo · 30 %",
  createdAt: "2026-11-20T14:50:00Z", startedAt: null, finishedAt: null, ...overrides,
});

describe("publication tabs", () => {
  it("opens the tab named in the URL, else the agenda", () => {
    expect(readTabFromLocation("?onglet=carousels")).toBe("carousels");
    expect(readTabFromLocation("?onglet=nope")).toBe("agenda");
    expect(readTabFromLocation("")).toBe("agenda");
  });

  it("sends a post to the tab where it is controlled", () => {
    expect(tabForPost({ status: "draft", mediaType: "reel" })).toBe("reels");
    expect(tabForPost({ status: "failed", mediaType: "carousel" })).toBe("carousels");
    expect(tabForPost({ status: "published", mediaType: "carousel" })).toBe("published");
    expect(postTitle({ mediaType: "carousel", carouselSeries: "week", raceTitle: null })).toBe("▦ La semaine qui vient");
  });

  it("lists running renders, failures, drafts, then the next 7 days of schedule", () => {
    const list = buildAttentionList({
      nowMs: NOW,
      renders: [
        render({ id: "running" }),
        render({ id: "broken", kind: "carousel", title: "La semaine qui vient · 23 nov.", status: "failed", stage: "Échec : réseau" }),
        render({ id: "finished", status: "done", stage: "Terminé" }),
      ],
      posts: [
        post({ id: "later", status: "scheduled", scheduledAt: "2026-11-24T17:00:00Z" }),
        post({ id: "soon", status: "scheduled", scheduledAt: "2026-11-21T17:00:00Z" }),
        post({ id: "far", status: "scheduled", scheduledAt: "2026-12-20T17:00:00Z" }),
        post({ id: "draft", status: "draft", autoGenerated: true }),
        post({ id: "failed", status: "failed", error: "Vidéo refusée" }),
        post({ id: "done", status: "published" }),
      ],
    });
    expect(list.map((entry) => entry.key)).toEqual(["render-running", "render-broken", "post-failed", "post-draft", "post-soon", "post-later"]);
    expect(list.find((entry) => entry.key === "render-broken")?.target).toEqual({ tab: "carousels", renderId: "broken" });
    expect(list.find((entry) => entry.key === "post-draft")?.detail).toBe("Brouillon automatique à relire");
    expect(list.find((entry) => entry.key === "post-failed")).toMatchObject({ tone: "error", target: { tab: "reels", postId: "failed" } });
  });

  it("brings a dismissed alert back when its state changes", () => {
    const key = (overrides: Partial<PublicSocialPost>) => buildAttentionList({ nowMs: NOW, renders: [], posts: [post({ id: "x", ...overrides })] })[0].dismissKey;
    expect(key({ status: "failed", error: "Vidéo refusée" })).toBe(key({ status: "failed", error: "Vidéo refusée" }));
    expect(key({ status: "failed", error: "Quota atteint" })).not.toBe(key({ status: "failed", error: "Vidéo refusée" }));
    expect(key({ status: "draft" })).not.toBe(key({ status: "failed", error: "Vidéo refusée" }));
  });
});

describe("console Publications tabs", () => {
  it("reads the tab and the item to highlight", () => {
    expect(readPostsTab("")).toBe("reels");
    expect(readPostsTab("?onglet=templates")).toBe("templates");
    expect(readPostsTab("?onglet=agenda")).toBe("reels");
    expect(readPostsHighlight("?post=p1&element=")).toEqual({ postId: "p1", itemId: null });
  });

  it("links an agenda target to its console page", () => {
    expect(publicationTargetHref({ tab: "reels", postId: "p1" })).toBe("/admin/content/posts?post=p1");
    expect(publicationTargetHref({ tab: "carousels", itemId: "i1" })).toBe("/admin/content/posts?onglet=carousels&element=i1");
    expect(publicationTargetHref({ tab: "published", postId: "p2" })).toBe("/admin/content/posts?onglet=published&post=p2");
    expect(publicationTargetHref({ tab: "reels" })).toBe("/admin/content/posts");
    expect(publicationTargetHref({ tab: "gpx" })).toBe("/admin/catalog/races?vue=qualite");
    expect(publicationTargetHref({ tab: "settings" })).toBe("/admin/system/automation");
  });

  it("links a render to the render queue and a flyover order to its card", () => {
    expect(publicationTargetHref({ tab: "reels", renderId: "r1" })).toBe("/admin/content/renders?rendu=r1");
    expect(publicationTargetHref({ tab: "flyovers", orderId: "o1" })).toBe("/admin/content/flyovers?commande=o1");
    expect(publicationTargetHref({ tab: "flyovers" })).toBe("/admin/content/flyovers");
  });

  it("names the manual carousel next to the automatic ones and keeps its old URL", () => {
    expect(POSTS_TABS.map((tab) => tab.label)).toEqual(["Reels", "Carrousels automatiques", "Carrousel manuel", "Publiées"]);
    expect(readPostsTab("?onglet=templates")).toBe("templates");
  });

  it("summarises the last 24 h of renders: running first, then failures, finished ones counted", () => {
    const base = { kind: "reel" as const, title: "T", progress: null, stage: "", createdAt: "2026-11-20T14:50:00Z", startedAt: null, finishedAt: null };
    const summary = summarizeRenderActivity([
      { ...base, id: "done", status: "done" },
      { ...base, id: "failed", status: "failed" },
      { ...base, id: "running", status: "active" },
      { ...base, id: "done2", status: "done" },
    ]);
    expect(summary.shown.map((job) => job.id)).toEqual(["running", "failed"]);
    expect(summary.doneCount).toBe(2);
  });
});
